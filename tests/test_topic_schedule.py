"""주제 요약의 일정을 시간 단서가 있는 약속·기한·기간과 단순 언급으로 구분한다."""

import pytest

from search.topic_brief import _planned_time


@pytest.mark.parametrize(
    "text",
    [
        "자료를 받으면 2~3일 정도 걸려요.",
        "자료를 주시면 이삼 일 정도 걸릴 것 같습니다.",
        "자료를 주시면 두세 시간 정도 걸립니다.",
        "내일 미팅을 잡았어요.",
        "어제 다음 주 월요일 미팅을 예약했습니다.",
        "이번 주 보안 리뷰 이후 추진",
        "이번 주에 보안 리뷰가 잡혀 있어서 이거 이후에 속도가 날 것 같습니다.",
        "이번 주 안에 해결하는 것이 목표입니다.",
        "금요일은 요청이고, 실제 발송은 다음 주에 합니다.",
        "금요일 요청, 실제 다음주 발송",
        "서류 승인이 나는 대로 제출하겠습니다.",
        "검수가 끝나면 발송하겠습니다.",
        "매주 월요일에 점검합니다.",
        "도면을 금요일까지 보내 주세요.",
    ],
)
def test_observed_schedule_and_conditional_lead_time(text: str) -> None:
    """과거형으로 예약한 미래 회의와 조건부 예상도 인용할 수 있다."""
    assert _planned_time(text)


@pytest.mark.parametrize(
    "text",
    [
        "같은 방식으로 사용을 해주시면 좋을 것 같습니다.",
        "링크만 한번 찾아주시면 제가 다시 재교육해달라고 할게요.",
        "수정한 파일을 전달해 주시면 감사하겠습니다.",
        "2시스템에서 처리하도록 하겠습니다.",
        "3주문을 같이 처리할 예정입니다.",
        "드롭다운에서 시간대를 선택할 수 있습니다.",
        "그때 정리해서 공유하겠습니다.",
        "오늘 오프라인 미팅을 했는데요.",
        "오늘 오프라인 미팅을 했는데 파일은 공유하겠습니다.",
        "지난 금요일에 맡긴 적이 있습니다.",
        "24시간 기준 데이터를 추출하겠습니다.",
        "최근 3일 평균을 업데이트하겠습니다.",
        "그 조건이 확인되면 오류가 납니다.",
        "실제 전송에 2시간이 걸렸습니다.",
        "금요일에 시작하기로 했는데 계획이 취소됐습니다.",
        "다음 주에 공유할 계획이 없어요.",
        "금요일까지 제출하는 건가요?",
    ],
)
def test_observation_courtesy_or_incidental_number_is_not_a_schedule(text: str) -> None:
    """정중한 조건, 수치로 시작하는 일반 명사, 회고, 측정값은 기한을 만들지 않는다."""
    assert not _planned_time(text)
