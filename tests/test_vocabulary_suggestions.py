"""전사 편집으로부터 사람이 검토할 표기 후보를 고르는 기준."""

import pytest

from core.vocabulary_suggestions import suggest_vocabulary_edits


@pytest.mark.parametrize(
    ("before", "after", "pairs"),
    [
        (
            "파이선은 패스트 에이피아이를 씁니다.",
            "파이썬은 FastAPI를 씁니다.",
            [("파이선", "파이썬"), ("패스트 에이피아이", "FastAPI")],
        ),
        (
            "파이선은 좋아요. 패스트 에이피아이를 씁니다.",
            "파이썬은 좋아요. FastAPI를 씁니다.",
            [("파이선", "파이썬"), ("패스트 에이피아이", "FastAPI")],
        ),
        ("팀에 배미룡을 소개합니다.", "팀에 배미령을 소개합니다.", [("배미룡", "배미령")]),
        ("오늘 젠 데스크가 왔어요.", "오늘 Zendesk가 왔어요.", [("젠 데스크", "Zendesk")]),
        (
            "잰데스크와 연결하고 잰데스크와 동기화합니다.",
            "젠데스크와 연결하고 젠데스크와 동기화합니다.",
            [("잰데스크", "젠데스크")],
        ),
        ("파이선", "파이썬", [("파이선", "파이썬")]),
        ("파이선 잰데스크", "파이썬 젠데스크", [("파이선", "파이썬"), ("잰데스크", "젠데스크")]),
        ("다음주에는 회의를 취소합니다.", "현장에서 점심을 먹었습니다.", []),
        ("카가오페이 결제", "카카오페이 결제", [("카가오페이", "카카오페이")]),
        ("개발 도구는 C++입니다.", "개발 도구는 C#입니다.", [("C++", "C#")]),
        ("닷넷을 씁니다.", ".NET을 씁니다.", [("닷넷", ".NET")]),
        ("우리 팀의 openai 사용량", "우리 팀의 OpenAI 사용량", [("openai", "OpenAI")]),
        ("새 모델을 확인.", "새 모델을 확인!", []),
        ("새 모델 확인", "새로운 세션을 시작했습니다", []),
        ("안건은 다음 주에 공유합니다", "안건은 월요일에 다음 주에 공유합니다", []),
        ("이번 주 미팅", "이번 미팅", []),
        ("파이썬을 씁니다.", "파이썬이 씁니다.", []),
        ("뉴 욕 타임스", "뉴욕 타임스", []),
        ("메모를 " * 500, "기타를 " * 500, []),
    ],
)
def test_edit_candidates(before: str, after: str, pairs: list[tuple[str, str]]) -> None:
    assert [(p.alias, p.term) for p in suggest_vocabulary_edits(before, after)] == pairs
